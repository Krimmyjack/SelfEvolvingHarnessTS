"""DEV-BATCH-RESEARCH-MEASURED-START: thin study module for run_batch_research_roundtrip --study measured_start.

Per job, four random complete plans R1..R4 are compiled from T only (frozen stream, no score filter). R1 and R2 are then
REALLY trained (3 paired seeds, C_A returned) before any search: they are the current-job random initialization,
occupying 2 of the 4 search slots of every method that receives them. Five arms on G7 (CSV string-sorted names
[224:256]) at a65/a85, empty H0, no Slow:
  F_start        R1/R2 with their real C_A are in the first request (candidates + overview.initialization); 2 free slots
  F_free         nothing supplied; 4 free slots
  Random-global  R1/R2 then frozen R3/R4; argmin three-seed C_A (Fixed, None, R1, R2, R3, R4)
  Random-local   R1/R2 then two random single-leaf neighbours of the C_A-best parent (one draw per step); argmin C_A
  Menu           fixed U-Mixup 0.25 / FreqMask 0.10; argmin C_A
  Start-only     (no branch) argmin C_A among None, Fixed, R1, R2 frozen when the initialization completes; 0 extra fits
The three initialized methods share the physical R1/R2 models/scores (experimental saving only); each still carries the
scientific cost of 2 slots / 6 fits. F_free and Menu never receive R1/R2. Both Fast arms reuse the derived build form and
semantic dedup of the paired_refinement adapter without its second-slot contract. R0/RB shadow selections are frozen per
arm before any label opens; they never change a delivery. Nothing numerical lives here.
"""
