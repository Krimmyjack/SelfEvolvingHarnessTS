# ----------------------------------------------------------------------------- frozen supply and initialization
def generate_supply(job, table):
    pool = dc.generate_pool(job, table, job_index=JOBS.index(job), seed_base=PROPOSAL_SEED_BASE)
    for d in pool['drafts']:
        d['draft_id'] = 'R' + d['draft_id'][1:]
    for a in pool['attempts']:
        if 'draft_id' in a:
            a['draft_id'] = 'R' + a['draft_id'][1:]
        if a['status'].startswith('duplicate_of_D'):
            a['status'] = 'duplicate_of_R' + a['status'][len('duplicate_of_D'):]
    pool['status'] = 'COMPLETE' if pool['status'] == 'COMPLETE' else 'SUPPLY_INCOMPLETE'
    pool['initialization'] = list(INIT_IDS)
    pool['visible_to_fast'] = 'R1, R2 with real C_A to f_start only (after real training); never to f_free or menu'
    return pool


def init_dir(root, job):
    return root / (job + '_init')


def initialize(root, job, led, shared, pool):
    """Task §4: after the common baselines, really train R1 and R2 of the job once (shared physical models of the three
    initialized methods), freeze the initialization record and the Start-only selection. Idempotent; 0 LLM."""
    init = init_dir(root, job)
    rec_path = init / 'initialization.json'
    if rec_path.exists():
        return context.read_json(rec_path)
    if pool is None or pool.get('status') != 'COMPLETE':
        return None
    if init.exists():   # an init copy without its record is a half-written attempt (killed mid-fit); its attempts stay on the ledger
        shutil.rmtree(init)
    if not init.exists():
        init.mkdir()
        shutil.copytree(shared / job, init / job)
    adapter = rt.Adapter(init, job, led, REPO, roster=ROSTERS.get(job), seeds=SEEDS)
    by_id = {c.plan_id: c for c in adapter.baselines()}
    drafts = {d['draft_id']: d for d in pool['drafts']}
    fits_before = led.s['fit_attempts']
    rec = {'job': job, 'role': INIT_ROLE, 'plans': {}, 'status': 'COMPLETE', 'epoch_started': time.time()}
    try:
        for mid in INIT_IDS:
            c = adapter.build_material({'plan_id': mid, 'policy': drafts[mid]['policy']}, remaining_seconds=led.remaining())
            if c.material_spec['assignment'] != drafts[mid]['assignment']:
                raise RuntimeError('frozen plan %s compiled to a different assignment' % mid)
            ms = adapter.specs[mid]
            ms['role'] = INIT_ROLE
            context.write_json(adapter.ctx.job_dir / 'materials' / (mid + '__compiled.json'), ms)
            c = br.Candidate(mid, ms, c.job_id)
            c = adapter.evaluate(c, SEEDS, feedback=True, remaining_seconds=led.remaining())
            by_id[mid] = c
            rec['plans'][mid] = {'model_refs': list(c.model_refs), 'feedback': c.feedback(SEEDS, 2, 32), 'n_identity': adapter.refs[mid].n_identity}
    except Exception as exc:
        rec.update({'status': 'INIT_FAILED', 'exception_type': type(exc).__name__, 'completed': [m for m in INIT_IDS if m in rec['plans']]})
    rec['fit_attempts_used'] = led.s['fit_attempts'] - fits_before
    rec['epoch_finished'] = time.time()
    if rec['status'] == 'COMPLETE':
        order = list(INIT_TIE_ORDER)
        chosen = min(order, key=lambda m: (by_id[m].feedback(SEEDS, 2, 32)['mean_loss'], order.index(m)))
        rec['start_only'] = {'selected': chosen, 'rule': 'argmin three-seed C_A mean among FixedMixup, None, R1, R2; ties in that order; frozen at initialization; 0 extra fits, 0 LLM',
                             'c_a_means': {m: by_id[m].feedback(SEEDS, 2, 32)['mean_loss'] for m in order}, 'delivery_model_ref': by_id[chosen].model_refs[0]}
    context.write_json(rec_path, rec)
    print('INIT', job, rec['status'], 'fits', rec['fit_attempts_used'], 'start_only', (rec.get('start_only') or {}).get('selected'), flush=True)
    return rec


def after_baselines(root, job, led, shared, pool):
    """Runner hook: called once per job right after the common baselines; the initialization must precede every arm of the job."""
    return initialize(root, job, led, shared, pool)


# ----------------------------------------------------------------------------- Fast adapter
class MeasuredAdapter(pr.RefineAdapter):
    """RefineAdapter's derived form + semantic dedup for both arms, no second-slot contract (arm is never 'f_refine').
    f_start: R1/R2 are restored from the initialization copy as fully evaluated candidates and marked in the overview."""
    def __init__(self, run_dir, job, ledger, repo, *, arm, **kw):
        rt.Adapter.__init__(self, run_dir, job, ledger, repo, **kw)
        if arm not in FAST_ARMS:
            raise ValueError('measured-start adapter needs f_start or f_free')
        self.arm = arm

    def baselines(self):
        common = super().baselines()
        if self.arm != 'f_start':
            return common
        before = self.ledger.s['fit_attempts']
        init = self.restore(list(INIT_IDS))          # cache hits only: the initialization was trained once in the init copy
        if self.ledger.s['fit_attempts'] != before or any(len(c.model_refs) != len(self.seeds) for c in init):
            raise RuntimeError('initialization must be restored from cache, never fitted here')
        return tuple(common) + tuple(init)

    def overview(self):
        ov = super().overview()
        if self.arm == 'f_start':
            ov['initialization'] = {'role': INIT_ROLE, 'plans': list(INIT_IDS), 'search_slots_total': 4, 'search_slots_used_by_initialization': 2,
                                    'search_slots_remaining_for_you': 2, 'note': INIT_NOTE}
        return ov


def arm_contracts(arm):
    out = pr.arm_contracts('f_free')
    if arm == 'f_start':
        out['evaluate']['meaning'] = ('Train the complete shared plan under 3 frozen paired seeds; return C_A only. At most 2 more new complete plans in this run: '
                                      '2 of the 4 search slots were used by the current-job random initialization R1/R2, which are already fully evaluated.')
        out['evaluate']['slot_contract'] = ('Search slots: 4 in total; 2 used by the initialization (R1, R2: random complete plans of this job, fully evaluated, listed in '
                                            'candidates with their real C_A). The remaining 2 are yours: build (complete policy or derived form, with R1/R2/FixedMixup or '
                                            'your own evaluated plans as possible parents), evaluate, compare or stop as useful. Any evaluated plan, including None, '
                                            'FixedMixup, R1 or R2, may be committed at any time. Nothing requires you to keep, modify or leave the initialization.')
        out['commit']['meaning'] = 'Final action. Pick any evaluated plan including None, FixedMixup, R1 or R2. No automatic argmin, no later selection override.'
    elif arm == 'f_free':
        out['evaluate']['meaning'] = 'Train the complete shared plan under 3 frozen paired seeds; return C_A only. At most 4 new complete plans in this run.'
        out['evaluate']['slot_contract'] = ('Search slots: 4, all yours: build (complete policy or derived form), evaluate, compare or stop as useful, in any order; any '
                                            'evaluated plan, including None or FixedMixup, may be committed at any time.')
    else:
        raise ValueError(arm)
    return out


