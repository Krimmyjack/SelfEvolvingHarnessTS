def _init_incomplete(path, job, rec):
    """An initialized method cannot run without its trained initialization: record INIT_INCOMPLETE, no substitute."""
    path.mkdir(parents=True, exist_ok=False)
    (path / 'trace.jsonl').write_text('', encoding='utf-8')
    result = br.RunResult('INCOMPLETE', job, 0, None, None, 0, 0, 0, [], 'INIT_INCOMPLETE', (rec or {}).get('status', 'MISSING'))
    context.write_json(path / 'branch_result.json', asdict(result))
    print('BRANCH', path.name, 'INIT_INCOMPLETE', flush=True)
    return result


def _init_control(root, job, led, init, *, tag):
    """Copy the initialized job (None/Fixed/R1/R2 cells) and restore R1/R2 as evaluated candidates; cache hits only."""
    root.mkdir(parents=True, exist_ok=False)
    shutil.copytree(init / job, root / job)
    adapter = rt.Adapter(root, job, led, REPO, roster=ROSTERS.get(job), seeds=SEEDS)
    by_id = {c.plan_id: c for c in adapter.baselines()}
    before = led.s['fit_attempts']
    for c in adapter.restore(list(INIT_IDS)):
        by_id[c.plan_id] = c
    if led.s['fit_attempts'] != before:
        raise RuntimeError('initialization must be restored from cache')
    trace = []

    def emit(event, **kw):
        row = {'event_id': f'{job}:{len(trace)}', 'event': event, **kw}
        trace.append(row)
        base.event_sink(root / 'trace.jsonl')(row)
    emit('initialization_restored', role=INIT_ROLE, plans=list(INIT_IDS), search_slots_used=2, feedback={m: by_id[m].feedback(SEEDS, 2, 32) for m in INIT_IDS})
    order = list(INIT_TIE_ORDER)

    def train(mid, pol, expected, **extra):
        c = adapter.build_material({'plan_id': mid, 'policy': pol}, remaining_seconds=led.remaining())
        if expected is not None and c.material_spec['assignment'] != expected:
            raise RuntimeError('frozen plan %s compiled to a different assignment' % mid)
        if extra:
            ms = pr.attach_derivation(adapter, mid, extra['parent_plan_id'], extra['parameter_edit'], extra['changed'], extra['branch_entities'])
            c = br.Candidate(mid, ms, c.job_id)
        emit(tag + '_material', plan_id=mid, material_spec=c.material_spec, **{k: v for k, v in extra.items() if k in ('parent_plan_id', 'parameter_edit')})
        c = adapter.evaluate(c, SEEDS, feedback=True, remaining_seconds=led.remaining())
        by_id[mid] = c
        order.append(mid)
        emit(tag + '_evaluated', plan_id=mid, feedback=c.feedback(SEEDS, 2, 32))
        return c

    def finish(reason, extra_new):
        chosen = min((by_id[m] for m in order), key=lambda c: (c.feedback(SEEDS, 2, 32)['mean_loss'], order.index(c.plan_id)))
        commit.commit(root, 'electricity', job, chosen.plan_id, reason, SEEDS[0])
        emit('committed', plan_id=chosen.plan_id, delivery_model_ref=chosen.model_refs[0])
        result = br.RunResult('COMPLETE', job, 0, chosen.plan_id, chosen.model_refs[0], 0, 0, extra_new, trace)
        context.write_json(root / 'branch_result.json', asdict(result))
        print(tag.upper(), job, 'commit', chosen.plan_id, flush=True)
        return result
    return adapter, by_id, order, train, finish, emit


def random_global_branch(root, job, led, init, pool):
    adapter, by_id, order, train, finish, emit = _init_control(root, job, led, init, tag='random')
    drafts = {d['draft_id']: d for d in pool['drafts']}
    for mid in ('R3', 'R4'):
        train(mid, drafts[mid]['policy'], drafts[mid]['assignment'])
    return finish('Random-global: minimum C_A three-seed mean among FixedMixup, None, R1, R2, R3, R4; frozen tie order; frozen random stream; 0 LLM.', 2)


def random_local_branch(root, job, led, init, pool):
    """Task §6: two random single-leaf steps from the C_A-best parent among this arm's complete plans; one draw per step."""
    adapter, by_id, order, train, finish, emit = _init_control(root, job, led, init, tag='local')
    table = adapter.overview()['entities']
    record = {'job': job, 'job_index': int(pool['job_index']), 'steps': [], 'status': 'COMPLETE'}
    for k in range(2):
        registered = {pid: policy.assignment_key(adapter.specs[pid]['assignment']) for pid in adapter.specs}
        census = {}
        for pid in order:
            nb = pr.enumerate_neighbours(adapter.specs[pid]['policy'], table, set(registered.values()), registered[pid])
            census[pid] = {'c_a_mean': by_id[pid].feedback(SEEDS, 2, 32)['mean_loss'], 'n_kept': sum(n['status'] == 'kept' for n in nb), 'n_enumerated': len(nb),
                           'neighbours': [{kk: n[kk] for kk in ('location', 'rule_index', 'step_index', 'op', 'parameter', 'old_value', 'new_value', 'status')} for n in nb], '_full': nb}
        eligible = [p for p in order if census[p]['n_kept']]
        step = {'k': k, 'seed': LOCAL_SEED_BASE + 1000 * int(pool['job_index']) + k, 'candidates': {p: {kk: v for kk, v in census[p].items() if kk != '_full'} for p in order}, 'eligible': eligible}
        emit('local_parent_selection', k=k, candidates=step['candidates'], eligible=eligible)
        if not eligible:
            step['status'] = 'LOCAL_NEIGHBORHOOD_EMPTY'
            record['steps'].append(step)
            record['status'] = 'LOCAL_NEIGHBORHOOD_EMPTY'
            break
        parent = min(eligible, key=lambda p: (census[p]['c_a_mean'], order.index(p)))
        kept = [n for n in census[parent]['_full'] if n['status'] == 'kept']
        idx = int(np.random.RandomState(step['seed']).randint(len(kept)))
        chosen = kept[idx]
        target = -1 if chosen['location'] == 'default' else chosen['rule_index']
        pa = adapter.specs[parent]['assignment']
        changed = [i for i, (a, b) in enumerate(zip(chosen['assignment'], pa)) if a != b]
        mid = 'L%d' % (k + 1)
        step.update({'parent': parent, 'n_kept': len(kept), 'drawn_index': idx, 'plan_id': mid,
                     'edit': {kk: chosen[kk] for kk in ('location', 'rule_index', 'step_index', 'op', 'parameter', 'old_value', 'new_value')}})
        record['steps'].append(step)
        train(mid, chosen['policy'], chosen['assignment'], parent_plan_id=parent, parameter_edit=step['edit'], changed=changed,
              branch_entities=[i for i, r in enumerate(adapter.specs[parent]['rule_index']) if r == target])
    context.write_json(root / 'local_search.json', record)
    return finish('Random-local: minimum C_A three-seed mean among FixedMixup, None, R1, R2, then evaluation order (%s); frozen tie order; 0 LLM.' % ', '.join(order[4:]), len(order) - 4)


def run_arm(arm, path, job, led, client, shared, pool, *, seeds, roster, max_tool_corrections):
    root = shared.parent
    init = init_dir(root, job)
    rec = context.read_json(init / 'initialization.json') if (init / 'initialization.json').exists() else None
    if arm in INIT_ARMS and (rec is None or rec.get('status') != 'COMPLETE'):
        return _init_incomplete(path, job, rec)
    if arm in FAST_ARMS:
        src = init if arm == 'f_start' else shared
        return base.branch(path, job, br.Knowledge(), led, client, src, evidence_roundtrip=True, max_tool_corrections=max_tool_corrections,
                           tool_contracts=arm_contracts(arm), seeds=seeds, roster=roster, adapter_factory=adapter_factory(arm, pool), limits=LIMITS[arm])
    if arm == 'random_global':
        return random_global_branch(path, job, led, init, pool)
    if arm == 'random_local':
        return random_local_branch(path, job, led, init, pool)
    if arm == 'menu':
        return dc.fixed_candidates_branch(path, job, led, shared, plans=list(MENU), tie_order=MENU_TIE_ORDER, tag='menu', seeds=seeds, roster=roster,
                                          reason='Fixed menu: minimum C_A three-seed mean among FixedMixup, None, MenuU, MenuFM; frozen tie order; no history read.')
    raise ValueError(arm)


def resume_arm(arm, path, job, led, client, pool, *, seeds, roster, max_tool_corrections):
    if arm not in FAST_ARMS:
        raise RuntimeError('control branch cannot be resumed')
    return base.resume_branch(path, job, br.Knowledge(), led, client, max_tool_corrections=max_tool_corrections, tool_contracts=arm_contracts(arm),
                              seeds=seeds, roster=roster, adapter_factory=adapter_factory(arm, pool), evidence_roundtrip=True, limits=LIMITS[arm])


# ----------------------------------------------------------------------------- R0 / RB shadow selection (frozen before labels; never a delivery)
def _cells(branch, job):
    out = {}
    for p in (branch / job / 'cells').glob('*.json'):
        c = context.read_json(p)
        if c.get('status') == 'OK' and c.get('scores', {}).get('c_a'):
            out.setdefault(c['material_id'], {})[c['model_seed']] = c
    return {m: s for m, s in out.items() if set(s) == set(SEEDS)}


def _tie_order(branch, job, arm, plans):
    if arm == 'menu':
        return [m for m in MENU_TIE_ORDER if m in plans]
    head = ['FixedMixup', 'None'] + ([m for m in INIT_IDS if m in plans] if arm in INIT_ARMS else [])
    rows = [json.loads(l) for l in (branch / 'trace.jsonl').read_text(encoding='utf-8').splitlines() if l.strip()]
    for x in rows:
        pid = x['output']['plan_id'] if x['event'] == 'tool_completed' and x['tool'] == 'evaluate' else x.get('plan_id') if x['event'].endswith('_evaluated') else None
        if pid and pid in plans and pid not in head:
            head.append(pid)
    return [m for m in head if m in plans] + [m for m in plans if m not in head]


def shadow_selection(branch, job, arm):
    cells = _cells(branch, job)
    if not cells:
        return None
    order = _tie_order(branch, job, arm, cells)
    ca = {m: [cells[m][s]['scores']['c_a']['normalized_mse_macro'] for s in SEEDS] for m in cells}
    last = {m: [cells[m][s]['scores']['c_a']['per_origin_normalized_mse_mean'][-1] for s in SEEDS] for m in cells}
    r0 = min(order, key=lambda m: (statistics.mean(ca[m]), order.index(m)))
    rb = min(order, key=lambda m: (statistics.mean(last[m]), order.index(m)))
    d = [[cells[r0][s]['scores']['c_a']['per_origin_normalized_mse_mean'][o] - cells[rb][s]['scores']['c_a']['per_origin_normalized_mse_mean'][o] for o in range(2)] for s in SEEDS]
    kind = 'SAME_SELECTION' if r0 == rb else 'CONSISTENT_CONFLICT' if all(row[0] < 0 and row[1] > 0 for row in d) else 'MIXED'
    commit_id = context.read_json(branch / job / 'commit.json')['material_id'] if (branch / job / 'commit.json').exists() else None
    return {'arm': arm, 'job': job, 'evaluated_set': order, 'R0': r0, 'RB': rb, 'kind': kind, 'd_r0_minus_rb_by_seed_origin': d,
            'c_a_mean': {m: statistics.mean(ca[m]) for m in order}, 'c_a_last_origin_mean': {m: statistics.mean(last[m]) for m in order},
            'actual_commit': commit_id, 'actual_commit_is_R0': commit_id == r0, 'actual_commit_is_RB': commit_id == rb,
            'frozen_before_labels': True, 'epoch': time.time(), 'note': 'selection replay on this arm\'s fixed evaluated set; never changes the delivery; 0 fits'}


def before_labels(root, branches):
    """Runner hook: freeze the R0/RB shadow selections of every completed branch before any C_B/E opens (idempotent)."""
    for p, job in branches:
        p = Path(p)
        if (p / 'shadow_selection.json').exists() or not (p / job / 'commit.json').exists():
            continue
        arm = p.name[len(job) + 1:]
        rec = shadow_selection(p, job, arm)
        if rec:
            context.write_json(p / 'shadow_selection.json', rec)
    context.write_json(root / 'shadow_selections_frozen.json', {'epoch': time.time(), 'branches': [str(p) for p, j in branches if (Path(p) / 'shadow_selection.json').exists()]})


# ----------------------------------------------------------------------------- report
def finish_report(root, r, jobs, order, seeds):
    r['study'] = 'measured_start'
    r.pop('treatment_present', None)
    pools = load_pools(root)
    r['random_supply'] = {j: ({k: p[k] for k in ('status', 'n_proposals_tried', 'initialization')} | {'plans': [{k: d[k] for k in ('draft_id', 'j', 'proposal_seed', 'n_rules', 'n_identity', 'n_entities_changed')} for d in p['drafts']]}) if p else None for j, p in pools.items()}
    r['initialization'] = {j: (context.read_json(init_dir(root, j) / 'initialization.json') if (init_dir(root, j) / 'initialization.json').exists() else None) for j in jobs}
    r['eligibility'] = {j: (context.read_json(root / (j + '_eligibility.json')) if (root / (j + '_eligibility.json')).exists() else {'status': 'ELIGIBLE'}) for j in jobs}
    r['skipped'] = {p.name[:-13]: context.read_json(p) for p in sorted(root.glob('*_skipped.json'))}
    r['supply_frozen'] = context.read_json(root / FROZEN_MARKER) if (root / FROZEN_MARKER).exists() else None
    r['resume'] = context.read_json(root / 'resume.json') if (root / 'resume.json').exists() else None
    r['target_checks'] = {j: context.read_json(root / (j + '_target_checks.json')) for j in jobs if (root / (j + '_target_checks.json')).exists()}
    r['shadow_frozen'] = context.read_json(root / 'shadow_selections_frozen.json') if (root / 'shadow_selections_frozen.json').exists() else None
    dc.annotate_branches(root, r, pools, seeds)
    seeds = tuple(seeds)

    def delta(cells_a, cells_b, block):
        ds = [cells_a[s][block]['normalized_mse_macro'] - cells_b[s][block]['normalized_mse_macro'] for s in seeds
              if s in cells_a and s in cells_b and cells_a[s].get(block) and cells_b[s].get(block)]
        if len(ds) != 3:
            return None
        return {'delta_by_seed': ds, 'mean_delta': statistics.mean(ds), 'seed_se': statistics.stdev(ds) / 3 ** .5, 'first_seed_delta': ds[0], 'positive_means': 'second_is_better'}

    def blocks(cells_a, cells_b):
        return {block: delta(cells_a, cells_b, block) for block in ('c_a', 'c_b', 'external')} if cells_a and cells_b else None

    def committed_cells(b):
        return sp._seed_cells(b, b['controller']['committed_plan_id']) if b and b['controller']['status'] == 'COMPLETE' else None

    for name, b in r['branches'].items():
        init_ids = INIT_IDS if b['arm'] in INIT_ARMS else ()
        b['initializer_evaluations'] = len(init_ids)
        b['fast_new_evaluations'] = b['controller']['new_evaluations'] if b['arm'] in FAST_ARMS else None
        b['search_materials'] = len(init_ids) + b['controller']['new_evaluations']
        b['logical_fit_cost'] = 6 + 3 * b['search_materials']
        b['process'] = pr.refinement_events(root, name, baseline_ids=BASELINE_IDS + init_ids) if b['arm'] in FAST_ARMS else None
        b['local_search'] = context.read_json(root / name / 'local_search.json') if (root / name / 'local_search.json').exists() else None
        b['shadow'] = context.read_json(root / name / 'shadow_selection.json') if (root / name / 'shadow_selection.json').exists() else None
        if b['shadow']:
            sh = b['shadow']
            sh['RB_minus_R0'] = blocks(sp._seed_cells(b, sh['RB']), sp._seed_cells(b, sh['R0']))
            sh['RB_minus_actual'] = blocks(sp._seed_cells(b, sh['RB']), committed_cells(b)) if b['controller']['status'] == 'COMPLETE' else None
        b['derived_edits'] = {}
        for p in b['new_candidate_materials']:
            comp = root / name / b['job'] / 'materials' / (p + '__compiled.json')
            ms = context.read_json(comp) if comp.exists() else {}
            if ms.get('parent_plan_id') is not None:
                b['derived_edits'][p] = {'parent_plan_id': ms['parent_plan_id'], 'parameter_edit': ms['parameter_edit'], 'n_entities_changed_arrays': ms['derivation']['n_entities_changed_arrays'],
                                         'parent_minus_child': blocks(sp._seed_cells(b, ms['parent_plan_id']), sp._seed_cells(b, p)), 'child_committed': b['controller']['committed_plan_id'] == p}
        cp = b['controller']['committed_plan_id']
        b['committed_origin'] = ('baseline' if cp in BASELINE_IDS else 'initialization' if cp in init_ids else 'new_material' if cp else None)
        e_by = {p: statistics.mean(c['external']['normalized_mse_macro'] for c in cells) for p, cells in b['plans'].items() if len(cells) == 3 and all(c.get('external') for c in cells)}
        b['within_arm_gap'] = (e_by[cp] - min(e_by.values())) if cp in e_by else None
    r['comparisons'] = {}
    for job in jobs:
        start = r['branches'].get(job + '_f_start')
        comp = {'positive_means': 'F_start has lower loss', 'reference': 'f_start committed plan'}
        ref = committed_cells(start)
        init_rec = r['initialization'].get(job) or {}
        so = (init_rec.get('start_only') or {}).get('selected')
        so_branch = next((r['branches'][job + '_' + a] for a in INIT_ARMS if job + '_' + a in r['branches'] and r['branches'][job + '_' + a]['controller']['status'] == 'COMPLETE'), None)
        so_cells = sp._seed_cells(so_branch, so) if so and so_branch else None
        comp['start_only'] = {'selected': so, 'e_mean': statistics.mean(c['external']['normalized_mse_macro'] for c in so_cells.values()) if so_cells and all(c.get('external') for c in so_cells.values()) else None}
        if ref:
            for arm in ('f_free', 'random_global', 'random_local', 'menu'):
                comp[arm + '_minus_f_start'] = blocks(committed_cells(r['branches'].get(job + '_' + arm)), ref)
            comp['start_only_minus_f_start'] = blocks(so_cells, ref) if so_cells else None
            for b0 in BASELINE_IDS + INIT_IDS:
                comp[b0 + '_minus_f_start'] = blocks(sp._seed_cells(start, b0), ref)
            comp['delta_free'] = comp['f_free_minus_f_start']
        else:
            comp['status'] = 'UNKNOWN: F_start branch missing or incomplete'
        keys, lineage, origin = {}, {}, {}
        for arm in ARMS:
            b = r['branches'].get(job + '_' + arm)
            if b and b['controller']['status'] == 'COMPLETE':
                p = b['controller']['committed_plan_id']
                keys[arm] = (b['new_candidate_materials'].get(p, {}).get('assignment_key') if p not in BASELINE_IDS else p)
                lineage[arm], origin[arm] = b['committed_lineage'], b['committed_origin']
        comp['committed_material_key_by_arm'], comp['committed_lineage_by_arm'], comp['committed_origin_by_arm'] = keys, lineage, origin
        pooled = {}
        for arm in ARMS:
            b = r['branches'].get(job + '_' + arm)
            for p, cells in (b or {}).get('plans', {}).items():
                if len(cells) == 3 and all(c.get('external') for c in cells):
                    pooled[arm + ':' + p] = statistics.mean(c['external']['normalized_mse_macro'] for c in cells)
        comp['retrospective_best_e_across_arms'] = (min(pooled, key=pooled.get), pooled[min(pooled, key=pooled.get)]) if pooled else None
        comp['shadow'] = {arm: ({k: r['branches'][job + '_' + arm]['shadow'][k] for k in ('R0', 'RB', 'kind', 'actual_commit', 'RB_minus_R0', 'RB_minus_actual')} if r['branches'].get(job + '_' + arm, {}).get('shadow') else None) for arm in ARMS}
        r['comparisons'][job] = comp
    planned = sum(len(order[j]) for j in jobs)
    r['planned_arms'], r['skipped_arms'] = planned, len(r['skipped'])
    r['status'] = 'COMPLETE' if (len(r['branches']) == planned and not r['failures'] and all(b['controller']['status'] == 'COMPLETE' and b['delivery_e'] is not None for b in r['branches'].values())) else 'PARTIAL'
    r['utility_supported'] = None
    r['utility_scope'] = 'Fixed research chain with a trained random initialization; one Fast trajectory per arm and job, three training seeds per complete plan, one population at two disjoint times; development pilot; no Slow.'
    context.write_json(root / 'result.json', r)
    lines = ['# DEV-BATCH-RESEARCH-MEASURED-START：机器汇总（result.json 派生）', '', '状态：' + r['status'], '',
             '|分支|状态|commit|来源|谱系|初始化槽|Fast新评估|搜索材料|逻辑拟合|第一seed E|三seed E均值|Fast请求|工具尝试|私有拟合|影子R0/RB/类型|集合内E遗憾|',
             '|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|']
    for name, b in r['branches'].items():
        sh = b.get('shadow') or {}
        lines.append('|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|' % (name, b['controller']['status'], b['controller']['committed_plan_id'], b['committed_origin'], (b['committed_lineage'] or {}).get('identical_to'),
                                                                         b['initializer_evaluations'], b['fast_new_evaluations'], b['search_materials'], b['logical_fit_cost'], b['delivery_e'], b['paired_mean_e'],
                                                                         b['controller']['calls'], b['controller']['tool_calls'], b['private_physical_fits'], '%s/%s/%s' % (sh.get('R0'), sh.get('RB'), sh.get('kind')), b['commit_regret_within_observed_candidates']))
    lines += ['', '各作业配对比较（正值 = F_start 损失更低）：']
    for j, x in r['comparisons'].items():
        lines.append(j + ': ' + json.dumps({k: v for k, v in x.items() if k.endswith('_minus_f_start') or k in ('delta_free', 'start_only')}, ensure_ascii=False))
    lines += ['', '预算：' + json.dumps(r.get('budget'), ensure_ascii=False), '', '主报告见 REPORT.md；本文件由 report() 自动生成，不含叙述判断。']
    (root / 'MACHINE_SUMMARY.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('MEASURED_START_REPORT', r['status'], flush=True)
    return r
