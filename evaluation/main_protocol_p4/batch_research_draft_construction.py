def environment():
    """Read-only confirmation of the fit worker's interpreter/torch/device, taken in a subprocess exactly as fits run
    (importing torch into the controller process would load a second OpenMP runtime next to numpy's MKL)."""
    if not _ENV:
        import subprocess
        code = 'import json,sys,torch;print(json.dumps({"python":sys.version.split()[0],"torch":torch.__version__,"device":"cuda" if torch.cuda.is_available() else "cpu"}))'
        out = subprocess.run([sys.executable, '-B', '-c', code], capture_output=True, text=True, timeout=300, cwd=REPO)
        if out.returncode:
            raise RuntimeError('environment confirmation failed')
        _ENV.update(json.loads(out.stdout.strip().splitlines()[-1]), fixed_for_all_arms=True, interpreter=sys.executable)
    return dict(_ENV)


