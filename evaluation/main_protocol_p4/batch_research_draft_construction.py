def target_checks(root, job, adapter):
    ov = adapter.overview()
    out = {'job': job, 'status': 'ELIGIBLE', 'roster': list(adapter.ctx.job.roster), 'roster_explicit': adapter.ctx.job.roster_override is not None,
           'n_entities': ov['n_entities'], 'train_rows': ov['train_rows'], 'stage': adapter.ctx.stage, 'fits': 0}
    context.write_json(root / (job + '_target_checks.json'), out)
    return out


def prepare(root, led, caps):
    """Stage 2 of the task: open both Targets' T only (eligibility, population binding), generate and freeze both draft
    pools, before any fit. Returns (common adapters of eligible jobs, pools by job; None = ELIGIBILITY_FAILED)."""
    context.write_json(root / 'frozen_config.json', frozen_config(caps))
    if led.s['fit_attempts']:
        raise RuntimeError('draft pools must be frozen before any fit')
    commons, pools = {}, {}
    for job in JOBS:
        shared = root / (job + '_common')
        shared.mkdir()
        try:
            adapter = rt.Adapter(shared, job, led, REPO, roster=ROSTERS[job], seeds=SEEDS)
        except RuntimeError as exc:
            if 'ELIGIBILITY_FAIL' not in str(exc):
                raise
            context.write_json(root / (job + '_eligibility.json'), {'job': job, 'status': 'ELIGIBILITY_FAILED', 'reason': str(exc), 'note': 'no population or time change; the other job continues'})
            pools[job] = None
            continue
        commons[job] = adapter
        ov = adapter.overview()
        target_checks(root, job, adapter)
        pools[job] = generate_pool(job, ov['entities'])
        context.write_json(root / (job + '_draft_pool.json'), pools[job])
    if led.s['fit_attempts']:
        raise RuntimeError('a fit happened during draft generation')
    context.write_json(root / 'drafts_frozen.json', {'epoch': time.time(), 'jobs': {j: (p['status'] if p else 'ELIGIBILITY_FAILED') for j, p in pools.items()},
                                                    'fit_attempts_at_freeze': led.s['fit_attempts'], 'note': 'both pools generated from T only before any fit; no C_A opened'})
    return commons, pools


def load_pools(root):
    return {job: (context.read_json(root / (job + '_draft_pool.json')) if (root / (job + '_draft_pool.json')).exists() else None) for job in JOBS}


# ----------------------------------------------------------------------------- arms
def fixed_candidates_branch(root, job, led, shared, *, plans, tie_order, tag, reason, seeds, roster, expected_assignments=None):
    """0-LLM control: build and co-train the listed plans, commit the argmin three-seed C_A mean among tie_order (frozen order)."""
    seeds = tuple(seeds)
    root.mkdir(parents=True, exist_ok=False)
    shutil.copytree(shared / job, root / job)
    adapter = rt.Adapter(root, job, led, REPO, roster=roster, seeds=seeds)
    by_id = {c.plan_id: c for c in adapter.baselines()}
    trace = []

    def emit(event, **kw):
        row = {'event_id': f'{job}:{len(trace)}', 'event': event, **kw}
        trace.append(row)
        base.event_sink(root / 'trace.jsonl')(row)
    for mid, pol in plans:
        c = adapter.build_material({'plan_id': mid, 'policy': pol}, remaining_seconds=led.remaining())
        if expected_assignments and c.material_spec['assignment'] != expected_assignments[mid]:
            raise RuntimeError('frozen draft %s compiled to a different assignment' % mid)
        emit(tag + '_material', plan_id=mid, material_spec=c.material_spec)
        c = adapter.evaluate(c, seeds, feedback=True, remaining_seconds=led.remaining())
        by_id[mid] = c
        emit(tag + '_evaluated', plan_id=mid, feedback=c.feedback(seeds, 2, 32))
    order = list(tie_order)
    chosen = min((by_id[m] for m in order), key=lambda c: (c.feedback(seeds, 2, 32)['mean_loss'], order.index(c.plan_id)))
    commit.commit(root, 'electricity', job, chosen.plan_id, reason, seeds[0])
    emit('committed', plan_id=chosen.plan_id, delivery_model_ref=chosen.model_refs[0])
    result = br.RunResult('COMPLETE', job, 0, chosen.plan_id, chosen.model_refs[0], 0, 0, len(plans), trace)
    context.write_json(root / 'branch_result.json', asdict(result))
    print(tag.upper(), job, 'commit', chosen.plan_id, flush=True)
    return result


def adapter_factory(arm, pool):
    if arm == 'f_free':
        return None
    return functools.partial(DraftAdapter, pool=pool, select_only=arm == 'f_select')


def run_arm(arm, path, job, led, client, shared, pool, *, seeds, roster, max_tool_corrections):
    if arm in FAST_ARMS:
        return base.branch(path, job, br.Knowledge(), led, client, shared, evidence_roundtrip=False, max_tool_corrections=max_tool_corrections,
                           tool_contracts=arm_contracts(arm), seeds=seeds, roster=roster, adapter_factory=adapter_factory(arm, pool))
    if arm == 'random':
        plans = [(d['draft_id'], d['policy']) for d in pool['drafts'][:2]]
        return fixed_candidates_branch(path, job, led, shared, plans=plans, tie_order=RANDOM_TIE_ORDER, tag='random', seeds=seeds, roster=roster,
                                       reason='Random draft baseline: minimum C_A three-seed mean among FixedMixup, None, D1, D2; frozen tie order; drafts from the frozen pool.',
                                       expected_assignments={d['draft_id']: d['assignment'] for d in pool['drafts'][:2]})
    if arm == 'menu':
        return fixed_candidates_branch(path, job, led, shared, plans=list(MENU), tie_order=MENU_TIE_ORDER, tag='menu', seeds=seeds, roster=roster,
                                       reason='Fixed menu: minimum C_A three-seed mean among FixedMixup, None, MenuU, MenuFM; frozen tie order; no history read.')
    raise ValueError(arm)


def resume_arm(arm, path, job, led, client, pool, *, seeds, roster, max_tool_corrections):
    if arm not in FAST_ARMS:
        raise RuntimeError('control branch cannot be resumed')
    return base.resume_branch(path, job, br.Knowledge(), led, client, max_tool_corrections=max_tool_corrections, tool_contracts=arm_contracts(arm),
                              seeds=seeds, roster=roster, adapter_factory=adapter_factory(arm, pool))


# ----------------------------------------------------------------------------- report
def _lineage(assignment, pool, table_size=32):
    """Where a built plan stands relative to the frozen drafts / baselines / menu, by expanded assignment only."""
    key = policy.assignment_key(assignment)
    named = {policy.assignment_key(d['assignment']): d['draft_id'] for d in (pool or {}).get('drafts', [])}
    named.update({v: k for k, v in (pool or {}).get('excluded_keys', {}).items()})
    for mid, pol in MENU:
        named.setdefault(policy.assignment_key([pol['default']['steps']] * table_size), mid)
    out = {'identical_to': named.get(key), 'n_identity': sum(1 for a in assignment if not a)}
    if pool and pool.get('drafts'):
        closest = min(pool['drafts'], key=lambda d: sum(a != b for a, b in zip(assignment, d['assignment'])))
        diff = [i for i, (a, b) in enumerate(zip(assignment, closest['assignment'])) if a != b]
        out['closest_draft'] = {'draft_id': closest['draft_id'], 'n_entities_differing': len(diff), 'entities_differing': diff}
    return out


def _policy_diff(new, old):
    return {'default_changed': new['default'] != old['default'], 'rules_changed': new['rules'] != old['rules'],
            'n_rules': [len(old['rules']), len(new['rules'])], 'ops_old': sorted({s['op'] for r in [old['default']] + old['rules'] for s in r['steps']}),
            'ops_new': sorted({s['op'] for r in [new['default']] + new['rules'] for s in r['steps']})}


def annotate_branches(root, r, pools, seeds):
    """Per-branch readouts shared by the draft studies: guidance/tool sequence, draft supply seen, built plans with
    lineage against the frozen pool, physical private fits, LLM cost, C_A-side selection facts. Mutates r['branches']."""
    seeds = tuple(seeds)
    for name, b in r['branches'].items():
        job, arm = name.split('_', 2)[0] + '_' + name.split('_', 2)[1], name.split('_', 2)[2]
        b['arm'], b['job'] = arm, job
        b.pop('mode_enabled', None)
        pool = pools.get(job)
        b['guidance'] = sp._guidance_readout(root, name)
        b['drafts_in_requests'] = any('unscored_drafts' in json.dumps(x.get('overview', {})) for x in (json.loads(l) for l in (root / name / 'trace.jsonl').read_text(encoding='utf-8').splitlines() if l.strip()) if x.get('event') == 'job_started')
        b['new_candidate_materials'] = {}
        for p, cells in b['plans'].items():
            if p in ('None', 'FixedMixup'):
                continue
            first = cells[0] if cells else {}
            rec = {'n_identity_entities': first.get('n_identity_entities'), 'material_alias_of': first.get('material_alias_of')}
            comp = root / name / job / 'materials' / (p + '__compiled.json')
            if comp.exists():
                ms = context.read_json(comp)
                rec.update({'policy': ms['policy'], 'assignment_key': policy.assignment_key(ms['assignment']), 'lineage': _lineage(ms['assignment'], pool)})
                if pool and rec['lineage'].get('closest_draft'):
                    dref = next(d for d in pool['drafts'] if d['draft_id'] == rec['lineage']['closest_draft']['draft_id'])
                    rec['policy_diff_vs_closest_draft'] = _policy_diff(ms['policy'], dref['policy'])
            b['new_candidate_materials'][p] = rec
        # built but never trained plans (materials only)
        idx = root / name / job / 'materials' / 'index.json'
        built = list(context.read_json(idx)) if idx.exists() else []
        b['built_not_trained'] = [m for m in built if m not in b['plans'] and m not in ('None', 'FixedMixup')]
        b['private_physical_fits'] = sum(1 for c in (root / name / job / 'cells').glob('*.json') if (lambda x: x.get('status') == 'OK' and x['material_id'] not in ('None', 'FixedMixup') and 'source_cell' not in x)(context.read_json(c)))
        tokens_in = tokens_out = n = 0
        for req in sorted((root / 'raw_responses').glob('*_request.json')):
            q = context.read_json(req)
            if q.get('unit') != name:
                continue
            resp = req.with_name(req.name.replace('_request.json', '_response.json'))
            if resp.exists():
                u = context.read_json(resp).get('usage') or {}
                n += 1
                tokens_in += int(u.get('prompt_tokens') or 0)
                tokens_out += int(u.get('completion_tokens') or 0)
        b['llm_cost'] = {'requests_with_response': n, 'prompt_tokens': tokens_in, 'completion_tokens': tokens_out}
        # C_A-side selection facts: committed vs argmin C_A among this arm's fully evaluated candidates
        ca = {p: statistics.mean(c['c_a']['normalized_mse_macro'] for c in cells) for p, cells in b['plans'].items() if len(cells) == 3 and all(c.get('c_a') for c in cells)}
        cp = b['controller']['committed_plan_id']
        b['c_a_means'] = ca
        b['committed_is_argmin_c_a'] = (cp is not None and cp in ca and ca[cp] == min(ca.values())) if ca else None
        b['committed_lineage'] = (b['new_candidate_materials'].get(cp, {}).get('lineage') if cp not in ('None', 'FixedMixup', None) else {'identical_to': cp})



def finish_report(root, r, jobs, order, seeds):
    r['study'] = 'draft_construction'
    r.pop('treatment_present', None)
    pools = load_pools(root)
    r['draft_pools'] = {j: ({k: p[k] for k in ('status', 'n_proposals_tried', 'fits', 'materials_built')} | {'drafts': [{k: d[k] for k in ('draft_id', 'j', 'proposal_seed', 'n_rules', 'n_identity', 'n_entities_changed')} for d in p['drafts']]}) if p else None for j, p in pools.items()}
    r['eligibility'] = {j: (context.read_json(root / (j + '_eligibility.json')) if (root / (j + '_eligibility.json')).exists() else {'status': 'ELIGIBLE'}) for j in jobs}
    r['skipped'] = {p.name[:-13]: context.read_json(p) for p in sorted(root.glob('*_skipped.json'))}
    r['drafts_frozen'] = context.read_json(root / 'drafts_frozen.json') if (root / 'drafts_frozen.json').exists() else None
    r['resume'] = context.read_json(root / 'resume.json') if (root / 'resume.json').exists() else None
    r['target_checks'] = {j: context.read_json(root / (j + '_target_checks.json')) for j in jobs if (root / (j + '_target_checks.json')).exists()}
    annotate_branches(root, r, pools, seeds)
    seeds = tuple(seeds)

    def delta(cells_a, cells_b, block):
        ds = [cells_a[s][block]['normalized_mse_macro'] - cells_b[s][block]['normalized_mse_macro'] for s in seeds
              if s in cells_a and s in cells_b and cells_a[s].get(block) and cells_b[s].get(block)]
        if len(ds) != 3:
            return None
        return {'delta_by_seed': ds, 'mean_delta': statistics.mean(ds), 'seed_se': statistics.stdev(ds) / 3 ** .5, 'first_seed_delta': ds[0], 'positive_means': 'second_is_better'}

    r['comparisons'] = {}
    for job in jobs:
        edit = r['branches'].get(job + '_f_edit')
        comp = {'positive_means': 'F_edit has lower loss', 'reference': 'f_edit committed plan'}
        if edit and edit['controller']['status'] == 'COMPLETE':
            ref = sp._seed_cells(edit, edit['controller']['committed_plan_id'])
            for arm in ('f_free', 'f_select', 'random', 'menu'):
                other = r['branches'].get(job + '_' + arm)
                comp[arm + '_minus_f_edit'] = ({block: delta(sp._seed_cells(other, other['controller']['committed_plan_id']), ref, block) for block in ('c_a', 'c_b', 'external')}
                                               if other and other['controller']['status'] == 'COMPLETE' else None)
            for b0 in ('None', 'FixedMixup'):
                comp[b0 + '_minus_f_edit'] = {block: delta(sp._seed_cells(edit, b0), ref, block) for block in ('c_a', 'c_b', 'external')}
            comp['delta_free'], comp['delta_select'] = comp['f_free_minus_f_edit'], comp['f_select_minus_f_edit']
            comp['delta_random'], comp['delta_menu'] = comp['random_minus_f_edit'], comp['menu_minus_f_edit']
        else:
            comp['status'] = 'UNKNOWN: F_edit branch missing or incomplete'
        keys, lineage = {}, {}
        for arm in ARMS:
            b = r['branches'].get(job + '_' + arm)
            if b and b['controller']['status'] == 'COMPLETE':
                p = b['controller']['committed_plan_id']
                keys[arm] = (b['new_candidate_materials'].get(p, {}).get('assignment_key') if p not in ('None', 'FixedMixup') else p)
                lineage[arm] = b['committed_lineage']
        comp['committed_material_key_by_arm'], comp['committed_lineage_by_arm'] = keys, lineage
        # retrospective diagnostic only: best E among every complete plan fitted by any arm of this job (no Agent saw it)
        pooled = {}
        for arm in ARMS:
            b = r['branches'].get(job + '_' + arm)
            for p, cells in (b or {}).get('plans', {}).items():
                if len(cells) == 3 and all(c.get('external') for c in cells):
                    pooled[arm + ':' + p] = statistics.mean(c['external']['normalized_mse_macro'] for c in cells)
        comp['retrospective_best_e_across_arms'] = (min(pooled, key=pooled.get), pooled[min(pooled, key=pooled.get)]) if pooled else None
        r['comparisons'][job] = comp
    planned = sum(len(order[j]) for j in jobs)
    r['planned_arms'], r['skipped_arms'] = planned, len(r['skipped'])
    r['status'] = 'COMPLETE' if (len(r['branches']) == planned and not r['failures'] and all(b['controller']['status'] == 'COMPLETE' and b['delivery_e'] is not None for b in r['branches'].values())) else 'PARTIAL'
    r['utility_supported'] = None
    r['utility_scope'] = 'One Fast trajectory per arm and job, three training seeds per complete plan, one population at two disjoint times; development pilot; no Slow.'
    context.write_json(root / 'result.json', r)
    lines = ['# DEV-BATCH-RESEARCH-DRAFT-CONSTRUCTION：机器汇总（result.json 派生）', '', '状态：' + r['status'], '',
             '|分支|状态|commit|谱系|第一seed E|三seed E均值|Fast请求|工具尝试|私有拟合|集合内E遗憾|',
             '|---|---|---|---|---:|---:|---:|---:|---:|---:|']
    for name, b in r['branches'].items():
        lines.append('|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|' % (name, b['controller']['status'], b['controller']['committed_plan_id'], (b['committed_lineage'] or {}).get('identical_to'),
                                                       b['delivery_e'], b['paired_mean_e'], b['controller']['calls'], b['controller']['tool_calls'], b['private_physical_fits'], b['commit_regret_within_observed_candidates']))
    lines += ['', '各作业配对比较（正值 = F_edit 损失更低）：']
    for j, x in r['comparisons'].items():
        lines.append(j + ': ' + json.dumps({k: v for k, v in x.items() if k.startswith('delta_') or k.endswith('_minus_f_edit')}, ensure_ascii=False))
    lines += ['', '预算：' + json.dumps(r.get('budget'), ensure_ascii=False), '', '主报告见 REPORT.md；本文件由 report() 自动生成，不含叙述判断。']
    (root / 'MACHINE_SUMMARY.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('DRAFT_CONSTRUCTION_REPORT', r['status'], flush=True)
    return r
