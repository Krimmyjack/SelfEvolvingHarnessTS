# ----------------------------------------------------------------------------- frozen draft pool (T only, 0 fits)
def generate_pool(job, table, *, job_index=None, seed_base=PROPOSAL_SEED_BASE):
    """Frozen draft flow (task §4) on `table` = overview()['entities'] of the job's T. Deterministic; reads nothing else.
    job_index / seed_base default to this study's values; another study passes its own without touching these globals."""
    job_index = JOBS.index(job) if job_index is None else int(job_index)
    excluded = {'None': policy.compile_policy(policy.identity_policy(), table)['key'],
                'FixedMixup': policy.compile_policy(policy.fixed_mixup_policy(), table)['key']}
    drafts, attempts, seen = [], [], {}
    for j in range(MAX_PROPOSALS):
        seed = seed_base + 1000 * job_index + j
        p = policy.random_policy(seed)
        p['rationale'] = DRAFT_RATIONALE          # the generator's constant label is replaced by a neutral one; default/rules untouched
        c = policy.compile_policy(p, table)
        dup = next((k for k, v in excluded.items() if v == c['key']), None) or seen.get(c['key'])
        rec = {'j': j, 'proposal_seed': seed, 'status': 'kept' if dup is None else 'duplicate_of_' + dup}
        if dup is None:
            did = 'D%d' % (len(drafts) + 1)
            seen[c['key']] = did
            n_identity = sum(1 for a in c['assignment'] if not a)
            drafts.append({'draft_id': did, 'j': j, 'proposal_seed': seed, 'policy': c['policy'], 'assignment': c['assignment'],
                           'rule_index': c['rule_index'], 'resolved_thresholds': c['resolved_thresholds'], 'n_unknown': c['n_unknown'],
                           'n_rules': len(c['policy']['rules']), 'n_identity': n_identity, 'n_entities_changed': len(table) - n_identity,
                           'entities_by_rule': {str(i): c['rule_index'].count(i) for i in range(-1, len(c['policy']['rules']))}})
            rec['draft_id'] = did
        attempts.append(rec)
        if len(drafts) == N_DRAFTS:
            break
    return {'job': job, 'job_index': job_index, 'status': 'COMPLETE' if len(drafts) == N_DRAFTS else 'DRAFT_POOL_INCOMPLETE',
            'n_proposals_tried': len(attempts), 'rule': DRAFT_RULE.replace(str(PROPOSAL_SEED_BASE), str(seed_base)), 'generator': GENERATOR_NOTE, 'excluded_keys': excluded,
            'attempts': attempts, 'drafts': drafts, 'fits': 0, 'materials_built': 0}


def drafts_view(pool):
    """What F_select / F_edit see in overview.unscored_drafts: the same four drafts, coverage facts, no scores."""
    return {'note': ('Four randomly generated, UNSCORED construction drafts compiled on the current T. They carry no historical evidence, '
                     'no quality order and no recommendation level; they are not evaluated candidates and have no models, scores or fit ids. '
                     'build_material turns a policy into a candidate; evaluate trains it. Reusing, changing or ignoring them are all legal.'),
            'generation': pool['generator'], 'n_proposals_tried': pool['n_proposals_tried'],
            'drafts': [{k: d[k] for k in ('draft_id', 'policy', 'n_rules', 'n_entities_changed', 'n_identity', 'entities_by_rule',
                                            'rule_index', 'resolved_thresholds', 'n_unknown')} for d in pool['drafts']]}


class DraftAdapter(rt.Adapter):
    """rt.Adapter plus the frozen draft pool in overview (F_select / F_edit). select_only admits, after compilation and
    before any material or fit, only assignments equal to a pool draft or a common baseline."""
    def __init__(self, run_dir, job, ledger, repo, *, pool, select_only=False, **kw):
        super().__init__(run_dir, job, ledger, repo, **kw)
        if pool.get('job') != self.ctx.job.job_id or pool.get('status') != 'COMPLETE':
            raise ValueError('draft pool does not belong to this job or is incomplete')
        self.pool, self.select_only = pool, bool(select_only)
        self.admitted = {policy.assignment_key(d['assignment']): d['draft_id'] for d in pool['drafts']}
        self.admitted.update({v: k for k, v in pool['excluded_keys'].items()})

    def overview(self):
        ov = super().overview()
        ov['unscored_drafts'] = drafts_view(self.pool)
        return ov

    def check_compiled(self, plan_id, compiled):
        if not self.select_only or compiled['key'] in self.admitted:
            return
        msg = ('this arm may only build plans whose expanded assignment equals one of the unscored drafts D1..D4 or a common baseline '
               '(None, FixedMixup); the compiled assignment of %r differs. Reuse a draft policy as given, or commit an evaluated candidate.' % plan_id)
        if self.tool_error_feedback:
            raise br.ToolInputError(msg, admitted_assignments=sorted(self.admitted.values()))
        raise ValueError(msg)


def arm_contracts(arm):
    """Neutral permission statements only; F_free keeps the shared contracts byte for byte."""
    out = br.json_copy(CONTRACTS)
    if arm == 'f_select':
        out['build_material']['draft_rule'] = ('This run: build_material accepts only policies whose compiled assignment equals one of overview.unscored_drafts '
                                              '(D1..D4) or a common baseline (None, FixedMixup); rationale text may differ. Any other compiled assignment is '
                                              'rejected before execution as a tool input error within the correction budget.')
    elif arm == 'f_edit':
        out['build_material']['draft_rule'] = ('This run: overview.unscored_drafts lists four unscored drafts. build_material accepts any legal policy: '
                                              'a draft as given, a modified draft (parameters, donor rule, operator, steps, rules), or a policy of your own.')
    return out


